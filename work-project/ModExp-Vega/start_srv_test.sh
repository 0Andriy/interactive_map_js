echo "=== Перезапуск API Vega ==="

# 1. Налаштовуємо змінні оточення (краще робити на початку)
export LD_LIBRARY_PATH=/home/adminapex/oracle/client_21.0
API_APP_DIR="/home/adminapex/ModExp-Vega"

# 2. Зупиняємо старий процес м'яко (шукаємо по частині шляху проєкту)
echo "Зупинка старого процесу..."
pkill -f "$API_APP_DIR" || true
# Зупиняємо старий процес м'яко (шукаємо саме node процес із назвою Vega)
pkill -f "Vega" || true

# 3. Очікуємо, щоб Node.js встиг звільнити мережеві порти
sleep 5

# 4. Примусово добиваємо, якщо завис
pkill -9 -f "$API_APP_DIR" || true
pkill -9 -f "Vega" || true

# 5. Переходимо в робочу директорію
cd "$API_APP_DIR" || { echo "Помилка: Не вдалося перейти в папку $API_APP_DIR"; exit 1; }

# 6. Запускаємо додаток у фоні та зберігаємо логи
nohup npm run start:test > Vega.log 2>&1 &  # > /dev/null 2>&1 &

# 7. Пауза 5 секунд, щоб npm встиг розгорнути node-процес
echo "Очікування ініціалізації додатку..."
sleep 5

# 8. Шукаємо PID процесу, який має назву Vega, АЛЕ ігноруємо сам цей bash-скрипт ($$)
# Фільтр 'node' гарантує, що ми шукаємо саме процес Node.js
NEW_PID=$(pgrep -f "Vega" | grep -v "$$")

if [ -n "$NEW_PID" ]; then
    echo "----------------------------------------"
    echo "✅ Додаток Vega УСПІШНО запущено!"
    echo "🆔 Новий PID процесу: $NEW_PID"
    echo "----------------------------------------"
else
    echo "----------------------------------------"
    echo "❌ ПОМИЛКА: Не вдалося запустити додаток Vega."
    echo "Останні рядки логу помилок (Vega.log):"
    tail -n 10 Vega.log
    echo "----------------------------------------"
fi
